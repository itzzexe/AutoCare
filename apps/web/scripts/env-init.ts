import { randomBytes } from "node:crypto";
import { existsSync, writeFileSync } from "node:fs";

/**
 * Creates apps/web/.env.local for LOCAL DEVELOPMENT with fresh random keys.
 * Never commit this file (it is git-ignored). Production secrets come from
 * the deployment's secret manager — see docs/DEPLOYMENT.md.
 */
const target = ".env.local";
if (existsSync(target) && !process.argv.includes("--force")) {
  console.error(`${target} already exists. Use --force to overwrite (existing encrypted data becomes unreadable).`);
  process.exit(1);
}
const b64 = (n: number) => randomBytes(n).toString("base64");
const lines = [
  "# Generated by pnpm env:init for local development only. Do not commit.",
  "APP_ENV=development",
  "APP_ORIGIN=http://localhost:3000",
  "TRUSTED_PROXY_HOPS=0",
  "# Empty DATABASE_URL = embedded PGlite in .data/pglite. For docker compose Postgres:",
  "# DATABASE_URL=postgres://autocare_app:autocare_app_dev@localhost:5432/autocare",
  "# DATABASE_MIGRATION_URL=postgres://autocare_owner:autocare_owner_dev@localhost:5432/autocare",
  "# REDIS_URL=redis://localhost:6379",
  `CSRF_SECRET=${b64(32)}`,
  `FILE_URL_SECRET=${b64(32)}`,
  `DATA_ENCRYPTION_KEYS=k1:${b64(32)}`,
  "DATA_ENCRYPTION_ACTIVE_KEY_ID=k1",
  "AI_MODE=local_only",
  "OLLAMA_URL=http://127.0.0.1:11434",
  "AI_MODEL=qwen3:8b",
  "AI_EMBED_MODEL=bge-m3",
  "PROVIDER_NHTSA_ENABLED=true",
  "ENABLE_MOCK_PROVIDERS=false",
  "ALLOW_DEMO_SEED=true",
  `PAYMENT_TEST_WEBHOOK_SECRET=${b64(32)}`,
  "# CLAMAV_HOST=127.0.0.1",
  "",
];
writeFileSync(target, lines.join("\n"), { mode: 0o600 });
console.log(`Wrote ${target}.`);
